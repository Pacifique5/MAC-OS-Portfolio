// Scans public/Photos and writes app/components/photos-data.ts.
// Run `npm run photos` whenever you add, remove or rename images in public/Photos.
//
// Albums are inferred from the image shape:
//   square    -> Badges
//   portrait  -> Documents
//   landscape -> Certificates
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const photosDir = join(root, 'public', 'Photos');
const outFile = join(root, 'app', 'components', 'photos-data.ts');

// Friendly titles for files whose names aren't descriptive.
const TITLE_OVERRIDES = {
  '7ea154a8-46f5-43de-842f-8b634b8af435': 'Skillsoft: Cloud Services & Deployment Fundamentals for SRE',
  '73-alx-aice-ai-career-essentials-certificate-mugisha-pacifique': 'ALX AI Career Essentials Certificate',
  'image (2)': 'Cisco Networking Academy Learning Transcript',
  'c-advanced': 'C++ Advanced',
};

const ACRONYMS = { alx: 'ALX', aice: 'AICE', ai: 'AI', iot: 'IoT', html: 'HTML', css: 'CSS', sre: 'SRE', c: 'C', javascript: 'JavaScript' };
const MINOR_WORDS = new Set(['and', 'to', 'of', 'for', 'in', 'the']);

/** Read pixel dimensions from PNG, JPEG or WebP headers (no dependencies). */
function dimensions(buf) {
  // PNG: IHDR chunk
  if (buf.readUInt32BE(0) === 0x89504e47) return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  // JPEG: walk segments to the first SOFn marker
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return { width: buf.readUInt16BE(i + 7), height: buf.readUInt16BE(i + 5) };
      }
      i += 2 + len;
    }
  }
  // WebP: RIFF....WEBP with VP8 / VP8L / VP8X chunk
  if (buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') {
    const chunk = buf.toString('ascii', 12, 16);
    if (chunk === 'VP8 ') return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
    if (chunk === 'VP8L') {
      const b = buf.readUInt32LE(21);
      return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 };
    }
    if (chunk === 'VP8X') return { width: buf.readUIntLE(24, 3) + 1, height: buf.readUIntLE(27, 3) + 1 };
  }
  return null;
}

function albumFor({ width, height }) {
  const ratio = width / height;
  if (ratio > 0.95 && ratio < 1.05) return 'badges';
  return ratio < 1 ? 'documents' : 'certificates';
}

/** Turn "python-essentials-1.1" into "Python Essentials 1.1"; random names get null. */
function humanize(name) {
  if (!name.includes('-')) return null;
  return name
    .split('-')
    .filter(Boolean)
    .map((w, i) => {
      const lower = w.toLowerCase();
      if (ACRONYMS[lower]) return ACRONYMS[lower];
      if (i > 0 && MINOR_WORDS.has(lower)) return lower;
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join(' ');
}

const files = readdirSync(photosDir).filter(f => ['.png', '.jpg', '.jpeg', '.webp'].includes(extname(f).toLowerCase()));

const photos = files
  .map(file => {
    const path = join(photosDir, file);
    const dims = dimensions(readFileSync(path));
    if (!dims) {
      console.warn(`Skipping ${file}: unsupported image format`);
      return null;
    }
    const name = basename(file, extname(file));
    return {
      file,
      name,
      ...dims,
      album: albumFor(dims),
      date: statSync(path).mtime.toISOString().slice(0, 10),
    };
  })
  .filter(Boolean)
  // Oldest first, like the Photos library (newest at the bottom)
  .sort((a, b) => a.date.localeCompare(b.date) || a.file.localeCompare(b.file));

const counters = { certificates: 0, badges: 0, documents: 0 };
const singular = { certificates: 'Certificate', badges: 'Badge', documents: 'Document' };

const entries = photos.map(p => {
  counters[p.album] += 1;
  const title = TITLE_OVERRIDES[p.name] ?? humanize(p.name) ?? `${singular[p.album]} ${counters[p.album]}`;
  return {
    id: p.name.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase(),
    src: `/Photos/${encodeURIComponent(p.file)}`,
    title,
    album: p.album,
    width: p.width,
    height: p.height,
    date: p.date,
  };
});

const out = `// Generated by scripts/generate-photos.mjs — do not edit by hand.
// Run \`npm run photos\` after adding, removing or renaming images in public/Photos.

export type PhotoAlbum = 'certificates' | 'badges' | 'documents';

export interface Photo {
  id: string;
  src: string;
  title: string;
  album: PhotoAlbum;
  width: number;
  height: number;
  /** YYYY-MM-DD */
  date: string;
}

export const PHOTOS: Photo[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(outFile, out);
console.log(`Wrote ${entries.length} photos to app/components/photos-data.ts`, counters);
